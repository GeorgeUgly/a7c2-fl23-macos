def simplify_message(message):
    text = str(message)
    for original in sorted(_MESSAGES, key=len, reverse=True):
        if text.startswith(original):
            tail = text[len(original):]
            # This upstream f-string has a dynamic chip/key between two literals.
            suffixes = {
                '發現額外設定變動：chip': '，請保存紀錄後檢查',
                '需要且只能連接一台目標相機（USB ': '）；請確認大量儲存模式及驅動',
            }
            suffix = suffixes.get(original)
            if suffix and tail.endswith(suffix):
                tail = tail[:-len(suffix)] + _MESSAGES[suffix]
            return _MESSAGES[original] + tail
    return text


